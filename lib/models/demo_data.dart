class FishingSpot {
  const FishingSpot(
    this.name,
    this.distance,
    this.score,
    this.type,
    this.wind,
    this.waves,
    this.fish,
    this.image, {
    this.point,
    this.mapped = false,
    this.sourceId,
    this.hasForecast = false,
    this.forecastCached = false,
  });
  final String name, distance, type, wind, waves, image;
  final int score;
  final List<String> fish;
  final LatLng? point;
  final bool mapped;
  final bool hasForecast, forecastCached;
  final String? sourceId;
}

class FishSpecies {
  const FishSpecies(
    this.name,
    this.scientific,
    this.habitat,
    this.difficulty,
    this.icon,
    this.color,
    this.probability,
    this.imagePath,
  );
  final String name, scientific, habitat, difficulty, probability, imagePath;
  final IconData icon;
  final Color color;
}

class Lesson {
  const Lesson(
    this.title,
    this.category,
    this.difficulty,
    this.duration,
    this.icon,
    this.progress, {
    this.id,
    this.description = '',
    this.steps = const [],
    this.practice = '',
    this.takeaway = '',
  });
  final String title, category, difficulty, duration;
  final IconData icon;
  final double progress;
  final String? id;
  final String description;
  final List<String> steps;
  final String practice;
  final String takeaway;
}

