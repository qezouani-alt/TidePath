"""Fetch curated, freely licensed species photographs from Wikimedia Commons."""
from __future__ import annotations

import html
import json
import re
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/images/fish'
OUT.mkdir(parents=True, exist_ok=True)

FILES = {
    'sea_bass': 'File:Dicentrarchus labrax 177025102.jpg',
    'sea_bream': 'File:Sparus aurata Sardegna.jpg',
    'mackerel': 'File:Scomber scombrus.jpg',
    'sardine': 'File:Sardina pilchardus Italy.jpg',
    'tuna': 'File:GFNMS bluefin tuna (49040302228).jpg',
    'snapper': 'File:Red snapper 2.jpg',
    'grouper': 'File:Epinephelus marginatus - Palmitos Park.jpg',
    'sole': 'File:Solea solea 1.jpg',
    'trout': 'File:Rainbow Trout (Oncorhynchus mykiss) Gavins Point.jpg',
    'carp': 'File:Karpfen (159381151).jpeg',
}
AGENT = 'TidePathFishingDemo/1.0 (Flutter app; attribution bundled with images)'


def get(url: str) -> bytes:
    for attempt in range(5):
        request = urllib.request.Request(url, headers={'User-Agent': AGENT})
        try:
            with urllib.request.urlopen(request, timeout=35) as response:
                return response.read()
        except urllib.error.HTTPError as error:
            if error.code not in (429, 503) or attempt == 4:
                raise
            time.sleep(4 * (attempt + 1))
    raise RuntimeError('Unreachable')


def plain(value: str) -> str:
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]*>', ' ', value))).strip()


parameters = urllib.parse.urlencode({
    'action': 'query',
    'titles': '|'.join(FILES.values()),
    'prop': 'imageinfo',
    'iiprop': 'url|extmetadata',
    'iiurlwidth': '900',
    'format': 'json',
})
data = json.loads(get('https://commons.wikimedia.org/w/api.php?' + parameters))
pages = {page['title']: page for page in data['query']['pages'].values()}
credits = ['# Fish photo credits', '', 'These bundled photographs are from Wikimedia Commons. Images are displayed with runtime cropping; no species image was generated by AI.', '']
structured_credits = []
for key, title in FILES.items():
    page = pages.get(title)
    if not page or 'imageinfo' not in page:
        raise RuntimeError(f'No Commons image found for {key}: {title}')
    info = page['imageinfo'][0]
    meta = info.get('extmetadata', {})
    license_name = plain(meta.get('LicenseShortName', {}).get('value', 'Unknown'))
    if not (license_name.startswith('CC ') or license_name in ('CC0', 'Public domain')):
        raise RuntimeError(f'Unexpected license for {title}: {license_name}')
    url = info.get('thumburl', info['url'])
    target = OUT / (key + '.jpg')
    target.write_bytes(get(url))
    artist = plain(meta.get('Artist', {}).get('value', 'Wikimedia Commons contributor'))
    license_url = meta.get('LicenseUrl', {}).get('value', '')
    source = info.get('descriptionurl', '')
    credits += [
        f'## {key.replace("_", " ").title()}',
        '',
        f'- Photo: [{title.removeprefix("File:")}]({source})',
        f'- Creator: {artist}',
        f'- License: [{license_name}]({license_url})' if license_url else f'- License: {license_name}',
        '',
    ]
    structured_credits.append({
        'name': key.replace('_', ' ').title(),
        'title': title.removeprefix('File:'),
        'creator': artist,
        'license': license_name,
        'source': source,
        'licenseUrl': license_url,
    })
    print(f'{key}: {title} ({license_name}, {target.stat().st_size} bytes)')
    time.sleep(1)
(OUT / 'ATTRIBUTION.md').write_text('\n'.join(credits))
(OUT / 'credits.json').write_text(json.dumps(structured_credits, indent=2))
